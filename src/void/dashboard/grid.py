"""The grid dashboard: one Kitty window on the right monitor, four bordered translucent tiles.

    ┌─────────────────────┐ ┌─────────────────────┐
    │ GEASS fastfetch +   │ │ btop                │      Kitty's grid layout tiles the four
    │ live shell prompt   │ │                     │      windows; window_margin_width makes the
    └─────────────────────┘ └─────────────────────┘      gaps, draw_minimal_borders=no gives each
    ┌─────────────────────┐ ┌─────────────────────┐      tile its own border, and the translucent
    │ matrix rain         │ │   21 29 50          │      background lets the wallpaper show through.
    │                     │ │   2026-10-19        │
    └─────────────────────┘ └─────────────────────┘

Every tile runs under `void pane …` (restarted if it exits). Konsole has no tiling, so without
Kitty the same four tiles run in tmux instead (session.build(layout="grid")).
"""

from __future__ import annotations

from .. import config, paths, tokens

VOID_BIN = paths.PROJECT_DIR / "bin" / "void"
TITLE = "VOID//DASHBOARD"
# Kitty's grid layout fills column by column: this order gives fetch top-left, btop top-right,
# rain bottom-left, clock bottom-right (checked against a real Kitty in tests).
TILES = [("shell", "GEASS"), ("rain", "DATA.STREAM"), ("sysmon", "SYSTEM.MON"), ("clock", "CHRONO")]


def conf_text(cfg: dict) -> str:
    p, t = tokens.pal(), tokens.load()["terminal"]
    minimal = config.current_profile(cfg) == "minimal"
    return "\n".join([
        f"# VOID grid dashboard — generated by VOID from config/tokens.toml (overrides void.conf). {tokens.HEADER}",
        f"font_size {float(t['grid_font_size'])}",
        "enabled_layouts grid", "hide_window_decorations yes", "tab_bar_min_tabs 99",
        f"window_margin_width {t['grid_gap']}", "single_window_margin_width -1",
        f"window_padding_width {t['grid_padding']}",
        "window_border_width 1.5pt", "draw_minimal_borders no",
        f"active_border_color {p['secondary_text']}", f"inactive_border_color {p['muted']}",
        f"bell_border_color {p['highlight']}", "inactive_text_alpha 1.0",
        f"background_opacity {1.0 if minimal else t['grid_opacity']}",
        f"background_blur {0 if minimal else t['grid_blur']}",
        "dynamic_background_opacity yes", "confirm_os_window_close 0", "remember_window_size no",
        "cursor_trail 0", "",
    ])


def session_text() -> str:
    lines = ["# VOID grid dashboard session — generated by VOID", "layout grid"]
    for i, (pane, title) in enumerate(TILES):
        lines.append(f'launch --title "{title}" {VOID_BIN} pane {pane}')
        if i == 0:
            lines.append("focus")   # keyboard starts in the shell tile
    lines.append("")
    return "\n".join(lines)


def files(cfg: dict) -> tuple[str, str]:
    d = paths.GENERATED
    d.mkdir(parents=True, exist_ok=True)
    conf, sess = d / "kitty-dashboard.conf", d / "kitty-dashboard.session"
    conf.write_text(conf_text(cfg))
    sess.write_text(session_text())
    return str(conf), str(sess)


def command(cfg: dict) -> list[str]:
    """Kitty command line for the grid dashboard (VOID's void.conf + the grid overrides only)."""
    from ..integration import kitty
    kitty.install()
    conf, sess = files(cfg)
    return ["kitty", "--config", str(kitty.THEME), "--config", conf, "--session", sess,
            "--class", "void-dashboard", "--title", TITLE]
